#!/usr/bin/env bash
# Interactive setup for the Samay app. gum-driven; back/quit on every menu.
# Writes .env (consumed via --dart-define-from-file). No secrets here: testing
# uses PUBLIC config only. Release signing material for staging/prod is
# provisioned out-of-band by the operator; this repo never fetches it.
set -euo pipefail
cd "$(dirname "$0")/.."

APP="samay"
KONG_PORT="${KONG_PORT:-54386}"
TESTING_URL="samay-api-testing.qallariy.lat"
PROD_URL="samay-api.qallariy.lat"
STACK_ENV="../backend/supabase/.env"
ROOT_ENV=".env"

# PUBLIC testing OAuth client ids (samay-testing GCP project; safe to ship).
TESTING_GOOGLE_OAUTH_CLIENT_ID="384058632735-dcmjlck6kod0ud9bco4374nfbcmdgcrl.apps.googleusercontent.com"
TESTING_GOOGLE_OAUTH_IOS_CLIENT_ID="384058632735-a8m49o8s6q7s5hmbbic0or2so64qedaj.apps.googleusercontent.com"

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }
[ -t 0 ] || { echo "make init requires an interactive terminal"; exit 1; }

clear
bold "== $APP app setup =="
echo
bold "Requirements"
ok=1
for t in flutter gum; do have "$t" && echo "  ok   $t" || { echo "  MISS $t (required)"; ok=0; }; done
echo
[ "$ok" -eq 1 ] || { echo "Install the required tools, then re-run 'make init'."; exit 1; }

mode="" url="" anon="" google_client_id="" google_ios_client_id=""
while :; do
  choice=$(gum choose --header "App backend (README → Requirements)" \
    "testing (hosted, public config — recommended)" \
    "local   (http://127.0.0.1:$KONG_PORT)" \
    "own     (your own backend + Firebase project)" \
    "quit")
  case "$choice" in
    testing*)
      mode=testing
      url="https://$TESTING_URL"
      google_client_id="$TESTING_GOOGLE_OAUTH_CLIENT_ID"
      google_ios_client_id="$TESTING_GOOGLE_OAUTH_IOS_CLIENT_ID"
      anon="$(sed -n 's/^SUPABASE_ANON_KEY=//p' "$ROOT_ENV" 2>/dev/null | head -1 || true)"
      [ -n "$anon" ] || anon="$(gum input --placeholder "SUPABASE_ANON_KEY (public)" --prompt "anon key> ")"
      break ;;
    local*)
      mode=local
      url="http://127.0.0.1:$KONG_PORT"
      google_client_id="$TESTING_GOOGLE_OAUTH_CLIENT_ID"
      google_ios_client_id="$TESTING_GOOGLE_OAUTH_IOS_CLIENT_ID"
      anon="$(sed -n 's/^SUPABASE_ANON_KEY=//p' "$STACK_ENV" 2>/dev/null | head -1 || true)"
      [ -n "$anon" ] || anon="$(gum input --placeholder "SUPABASE_ANON_KEY (local stack)" --prompt "anon key> ")"
      break ;;
    own*)
      mode=own
      url="$(gum input --placeholder "https://api.example.com" --prompt "backend url> ")"
      [ -n "$url" ] || { echo "aborted"; exit 0; }
      anon="$(gum input --placeholder "Supabase anon key (public)" --prompt "anon key> ")"
      google_client_id="$(gum input --placeholder "your GCP Web client id (serverClientId)" --prompt "GOOGLE_OAUTH_CLIENT_ID> ")"
      google_ios_client_id="$(gum input --placeholder "your GCP iOS client id (blank to skip iOS)" --prompt "GOOGLE_OAUTH_IOS_CLIENT_ID> ")"
      break ;;
    *) echo "aborted"; exit 0 ;;
  esac
done

umask 177
{
  echo "# generated by make init ($(date -u +%FT%TZ))"
  echo "SUPABASE_URL=$url"
  [ -n "$anon" ] && echo "SUPABASE_ANON_KEY=$anon"
  [ -n "$google_client_id" ] && echo "GOOGLE_OAUTH_CLIENT_ID=$google_client_id"
  [ -n "$google_ios_client_id" ] && echo "GOOGLE_OAUTH_IOS_CLIENT_ID=$google_ios_client_id"
  echo "API_TESTING_URL=https://$TESTING_URL"
  echo "API_PROD_URL=https://$PROD_URL"
} > "$ROOT_ENV"
chmod 600 "$ROOT_ENV"
echo
echo "wrote $ROOT_ENV (mode=$mode, url=$url)"
[ "$mode" = "own" ] && echo "own-project setup: see README → Requirements (google-services.json / GoogleService-Info.plist + SHA-1)"
echo "next: make start            # run against the chosen backend"
