#!/usr/bin/env bash
# Interactive local setup for the Samay app. gum-driven; back/quit on every menu.
# Writes .env (consumed via --dart-define-from-file). Prod uses the vault-gated
# release lane; this only wires a local/run URL.
set -euo pipefail
cd "$(dirname "$0")/.."

APP="samay"
KONG_PORT="${KONG_PORT:-54386}"
TESTING_URL="samay-api-testing.qallariy.lat"
PROD_URL="samay-api.qallariy.lat"
STACK_ENV="../backend/supabase/.env"
ROOT_ENV=".env"

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }
[ -t 0 ] || { echo "make init requires an interactive terminal"; exit 1; }

clear
bold "== $APP app setup =="
echo
bold "Requirements"
ok=1
for t in flutter gum; do have "$t" && echo "  ok   $t" || { echo "  MISS $t (required)"; ok=0; }; done
echo
[ "$ok" -eq 1 ] || { echo "Install the required tools, then re-run 'make init'."; exit 1; }

anon="$(sed -n 's/^SUPABASE_ANON_KEY=//p' "$STACK_ENV" 2>/dev/null | head -1 || true)"

mode="" url=""
while :; do
  choice=$(gum choose --header "App backend" \
    "local  (http://127.0.0.1:$KONG_PORT)" \
    "tunnel (https://$TESTING_URL)" \
    "prod   (https://$PROD_URL)" \
    "quit")
  case "$choice" in
    local*)  mode=local;  url="http://127.0.0.1:$KONG_PORT"; break ;;
    tunnel*) mode=tunnel; url="https://$TESTING_URL"; break ;;
    prod*)   mode=prod;   url="https://$PROD_URL"; break ;;
    *) echo "aborted"; exit 0 ;;
  esac
done

if [ -z "$anon" ]; then
  anon=$(gum input --placeholder "SUPABASE_ANON_KEY (publishable)" --prompt "anon key> ") || true
fi

umask 177
{
  echo "# generated by make init ($(date -u +%FT%TZ))"
  echo "SUPABASE_URL=$url"
  [ -n "$anon" ] && echo "SUPABASE_ANON_KEY=$anon"
} > "$ROOT_ENV"
chmod 600 "$ROOT_ENV"
echo
echo "wrote $ROOT_ENV (mode=$mode, url=$url)"
echo "next: make start            # run against the chosen backend"
